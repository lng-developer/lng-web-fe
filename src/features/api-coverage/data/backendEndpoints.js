export const BACKEND_ENDPOINTS = ROUTE_TABLE.trim()
  .split('\n')
  .map((line) => {
    const [moduleId, method, path] = line.split('|')
    return {
      id: `${method} ${path}`,
      moduleId,
      method,
      path,
      paramNames: [...path.matchAll(/:([A-Za-z0-9_]+)/g)].map((match) => match[1]),
    }
  })

export const BACKEND_ENDPOINT_MODULES = [
  ...new Set(BACKEND_ENDPOINTS.map((endpoint) => endpoint.moduleId)),
]

export function materializeEndpointPath(endpoint, params = {}) {
  return endpoint.paramNames.reduce(
    (path, name) => path.replace(`:${name}`, encodeURIComponent(params[name] || '')),
    endpoint.path,
  )
}
